/** * Draws reconstructed cells on a graphical display.
 *
 * @param cellall Collection of geometry cells to be drawn.
 * @param toymatrix Pointer to the toy matrix containing cell charge information.
 * @param option Drawing options passed to ROOT's Draw method.
 * @param color Color index for the markers representing the cells.
 * @return Always returns 0.
 * This comment was generated by Qwen/Qwen2.5-Coder-32B-Instruct:None at temperature 0.01.
*/ 
int ToyEventDisplay::draw_reconcells(const WCP::GeomCellSelection& cellall, WCP2dToy::ToyMatrix *toymatrix ,TString option, int color){
  
  pad.cd();
  g2 = new TGraph();
  int ncount = 0;
  for (int i=0;i!=cellall.size();i++){
    WCP::MergeGeomCell *mcell = (WCP::MergeGeomCell*)cellall[i];
    if (toymatrix->Get_Cell_Charge(mcell)>recon_threshold){
      WCP::GeomCellSelection acell = mcell->get_allcell();
      for (int j=0;j!=acell.size();j++){
	g2->SetPoint(ncount,acell[j]->center().z/units::m,acell[j]->center().y/units::m);
	ncount ++;
      }
    }
  }
  
  g2->SetMarkerColor(color);
  g2->SetMarkerSize(0.8);
  g2->Draw(option);
  g2->SetMarkerStyle(21);
  
  return 0;

  
}
