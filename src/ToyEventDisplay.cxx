/** * Initializes the event display with specified axis limits.
 * Clears any existing data, sets up histograms for wire and true hit visualization,
 * configures axes divisions, titles, and range settings.
 *
 * @param x_min Minimum value for the X-axis.
 * @param x_max Maximum value for the X-axis.
 * @param y_min Minimum value for the Y-axis.
 * @param y_max Maximum value for the Y-axis.
 * @return Always returns 0 indicating successful initialization.
 * This comment was generated by Qwen/Qwen2.5-Coder-32B-Instruct:None at temperature 0.01.
*/ 
int ToyEventDisplay::init(float x_min, float x_max, float y_min, float y_max)
{
  this->clear();

  h1 = new TH2F("h1","h1",1000,x_min,x_max,1000,y_min,y_max);
  if (gds_flag == 0){
    h1->SetTitle("Wires and True Hits ");
  }else{
    h1->SetTitle("Wires and True Hits (B face +x)");
  }
  h1->GetYaxis()->SetNdivisions(506);
  h1->GetXaxis()->SetNdivisions(506);
  h1->SetXTitle("Z (m)");
  h1->SetYTitle("Y (m)");
  h1->SetBinContent(0,0,1);
  h1->GetZaxis()->SetRangeUser(charge_min,charge_max);

  if (gds_flag == 1){
    h2 = new TH2F("h2","h2",1000,x_min,x_max,1000,y_min,y_max);
    h2->SetTitle("Wires and True Hits (A face -x)");
    h2->GetYaxis()->SetNdivisions(506);
    h2->GetXaxis()->SetNdivisions(506);
    h2->SetXTitle("Z (m)");
    h2->SetYTitle("Y (m)");
    h2->SetBinContent(0,0,1);
    h2->GetZaxis()->SetRangeUser(charge_min,charge_max);
  }

  return 0;
}

/** * Draws Monte Carlo truth information on a canvas.
 *
 * @param flag Determines the drawing method: 1 for histogram draw, 2 for filling histogram with MC truth points, 3 for graph draw.
 * @param mctruth Vector containing Monte Carlo truth points and associated values.
 * @param option Drawing options passed to ROOT functions.
 * @return Always returns 0.
 * This comment was generated by Qwen/Qwen2.5-Coder-32B-Instruct:None at temperature 0.01.
*/ 
int ToyEventDisplay::draw_mc(int flag, const WCP::PointValueVector& mctruth, TString option)
{
  if (gds_flag == 0 ){
    pad.cd();

    if (flag==1){
      h1->Draw(option);
      
    }else if (flag==2){
      h1->Reset();
      for (int i=0;i!=mctruth.size();i++){
	h1->Fill(mctruth[i].first.z/units::m,mctruth[i].first.y/units::m-0.02,int(mctruth[i].second*10)/10.);
      }
      h1->Draw(option);
    }else if (flag==3){
      //if (g1) delete g1;
      g1 = new TGraph();
      for (int i=0;i!=mctruth.size();i++){
	g1->SetPoint(i,mctruth[i].first.z/units::m,mctruth[i].first.y/units::m);
      }
      g1->SetMarkerColor(2);
      g1->SetMarkerSize(0.6);
      g1->Draw(option);
      g1->SetMarkerStyle(20);
    }
  }else{
    pad.cd(1);
    h1->Draw(option);
    
    pad.cd(2);
    h2->Draw(option);
  }
  
  return 0;
}


/** * Draws bad cells on the event display canvas.
 *
 * Iterates through a collection of geometric cell selections, extracts their boundary coordinates,
 * and draws them as filled polygons on the current ROOT pad.
 *
 * @param cells Reference to a selection of geometric cells marked as bad.
 * This comment was generated by Qwen/Qwen2.5-Coder-32B-Instruct:None at temperature 0.01.
*/ 
void ToyEventDisplay::draw_bad_cell(WCP::GeomCellSelection& cells){
  pad.cd();
  for (int i=0;i!=cells.size();i++){
    double x[100];
    double y[100];
    
    for (int j=0;j!=cells.at(i)->boundary().size();j++){
      x[j] = cells.at(i)->boundary().at(j).z/units::m;
      y[j] = cells.at(i)->boundary().at(j).y/units::m;
      //std::cout << x[j] << " " << y[j] << std::endl;
    }
    x[cells.at(i)->boundary().size()] = x[0];
    y[cells.at(i)->boundary().size()] = y[0];
    // std::cout << x[4] << " " << y[4] << std::endl;
    // std::cout << std::endl;

    TPolyLine *pline = new TPolyLine(cells.at(i)->boundary().size()+1,x,y);
    pline->SetFillColor(5);
    pline->SetLineColor(5);
    //pline->SetLineWidth(1);
    pline->Draw("fsame");
    pline->Draw("same");
  }
}

