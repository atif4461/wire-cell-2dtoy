/** * Draws multiple wires on an event display canvas.
 *
 * This method iterates over a collection of geometric wires, calculates their positions based on plane-specific parameters such as pitch and angle,
 * and draws them using ROOT's TLine objects. Each wire is represented by three lines: two outer lines representing the extent of the wire's width and one central line.
 *
 * @param wires Reference to a selection of geometric wires to be drawn.
 * @param option Drawing options passed to the TLine Draw() method.
 * @return Always returns 0 indicating successful execution.
 * This comment was generated by Qwen/Qwen2.5-Coder-32B-Instruct:None at temperature 0.01.
*/ 
int ToyEventDisplay::draw_wires(WCP::GeomWireSelection& wires, TString option){
  
 
    for (int j=0;j!=wires.size();j++){
      
      const WCP::GeomWire *wire = wires.at(j);
      
      
      
       float pitch = gds->pitch(wire->plane());
      float angle = gds->angle(wire->plane());
      //std::cout << pitch/units::mm << " " << angle << std::endl;
      
      TLine *l1 = new TLine(wire->point1().z/units::m - pitch/2./units::m/std::cos(angle/units::radian) ,wire->point1().y/units::m,
			    wire->point2().z/units::m - pitch/2./units::m/std::cos(angle/units::radian) ,wire->point2().y/units::m);
      l1->Draw(option);
      l1->SetLineStyle(1);
      
      TLine *l2 = new TLine(wire->point1().z/units::m + pitch/2./units::m/std::cos(angle/units::radian) ,wire->point1().y/units::m,
			    wire->point2().z/units::m + pitch/2./units::m/std::cos(angle/units::radian) ,wire->point2().y/units::m);
      l2->Draw(option);
      l2->SetLineStyle(1);
      
      TLine *l3 = new TLine(wire->point1().z/units::m  ,wire->point1().y/units::m,
			    wire->point2().z/units::m  ,wire->point2().y/units::m);
      l3->SetLineColor(2);
      l3->Draw(option);
      l3->SetLineStyle(1);
    }
    
    // break;
    



  
  return 0;
}

