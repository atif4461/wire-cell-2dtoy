/** * Draws merged cells on two pads based on specified options and flags.
 *
 * @param cellall Collection of geometry cells to draw.
 * @param option Drawing option string passed to TGraph::Draw().
 * @param flag Flag indicating drawing criteria; 0 for all cells, 1 for cells containing truth information.
 * @return Always returns 0.
 * This comment was generated by Qwen/Qwen2.5-Coder-32B-Instruct:None at temperature 0.01.
*/ 
int ToyEventDisplay::draw_mergecells(const WCP::GeomCellSelection& cellall, TString option, int flag)
{
 
  
  int np = 0;
  int npb = 0;
  g2 = new TGraph();
  g2b = new TGraph();
  
  for (int i=0;i!=cellall.size();i++){
    const WCP::MergeGeomCell* mcell = (const WCP::MergeGeomCell*)cellall.at(i);
    int face = mcell->get_allcell().at(0)->get_face();

    if (flag==0){
      
      if (face == 1){
	g2->SetPoint(np,cellall[i]->center().z/units::m,cellall[i]->center().y/units::m);
	//std::cout << cellall[i]->center().z/units::m << " " << cellall[i]->center().y/units::m << std::endl;
	np++;
      }else{
	g2b->SetPoint(npb,cellall[i]->center().z/units::m,cellall[i]->center().y/units::m);
	//std::cout << cellall[i]->center().z/units::m << " " << cellall[i]->center().y/units::m << std::endl;
	npb++;
      }
    }else if (flag==1){
      WCP::MergeGeomCell *mcell = (WCP::MergeGeomCell*)cellall[i];
      if (mcell->GetContainTruthCell()){
	if (face == 1){
	  g2->SetPoint(np,cellall[i]->center().z/units::m,cellall[i]->center().y/units::m);
	  np++;
	}else{
	  g2b->SetPoint(npb,cellall[i]->center().z/units::m,cellall[i]->center().y/units::m);
	  npb++;
	}
      }
    }
  }

  
  pad.cd(1);
  g2->SetMarkerColor(2);
  g2->SetMarkerSize(0.8);
  if (g2->GetN()!=0)
    g2->Draw(option);
  g2->SetMarkerStyle(24);
  
  pad.cd(2);
  g2b->SetMarkerColor(2);
  g2b->SetMarkerSize(0.8);
  if (g2b->GetN()!=0)
    g2b->Draw(option);
  g2b->SetMarkerStyle(24);

  return 0;
}



/** * Draws truth cells on a graphical display based on cell charge map and specified options.
 *
 * @param ccmap CellChargeMap containing cell information and their associated charges.
 * @param option Drawing options passed to the TGraph Draw method.
 * @return Always returns 0.
 * This comment was generated by Qwen/Qwen2.5-Coder-32B-Instruct:None at temperature 0.01.
*/ 
int ToyEventDisplay::draw_truthcells(const WCP::CellChargeMap& ccmap, TString option)
{
  if (gds_flag==1){
    g2 = new TGraph();
    g2b = new TGraph();
    int nf = 0;
    int nb = 0;
    
    int i=0;
    for (auto it = ccmap.begin();it!=ccmap.end(); it++){
      WCP::Point p = it->first->center();
      if (it->first->get_face()==1){
	if (it->second > truth_threshold){
	  g2->SetPoint(nf,p.z/units::m,p.y/units::m);
	  nf++;
	}
      }else{
	if (it->second > truth_threshold){
	  g2b->SetPoint(nb,p.z/units::m,p.y/units::m);
	  nb++;
	}
      }
      
    }
    pad.cd(1);
    g2->SetMarkerColor(8);
    //g2->SetMarkerColor(1);
    g2->SetMarkerSize(0.8);
    g2->Draw(option);
    g2->SetMarkerStyle(26);

    pad.cd(2);
    g2b->SetMarkerColor(8);
    //g2->SetMarkerColor(1);
    g2b->SetMarkerSize(0.8);
    if (g2b->GetN()!=0)
      g2b->Draw(option);
    g2b->SetMarkerStyle(26);

  }else{
    pad.cd();
    
    g2 = new TGraph();
    int i=0;
    for (auto it = ccmap.begin();it!=ccmap.end(); it++){
      WCP::Point p = it->first->center();
      if (it->second > truth_threshold){
	g2->SetPoint(i,p.z/units::m,p.y/units::m);
	i++;
      }
    }
    g2->SetMarkerColor(8);
    //g2->SetMarkerColor(1);
    g2->SetMarkerSize(0.8);
    g2->Draw(option);
    g2->SetMarkerStyle(26);
  }
  
  return 0;
}

